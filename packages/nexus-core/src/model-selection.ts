/**
 * 每會話模型選擇的**機制**：下一步起用哪一顆模型與推理強度、怎麼換、換了怎麼告訴模型
 * （[#723](https://github.com/DemianLi/nexus-agent/issues/723)）。
 *
 * 照 dsh `installModelSelection`（`packages/core/agent/src/model-selection.ts:81-143`，`5badb15`）。三件事，對到它的三個監聽：
 *
 * 1. **每一步開頭快照選擇，這一步的請求用快照**（dsh `system-prompt/assemble` 記下 `assembled`，`agent/request` 套用它）。選擇從
 *    **下一步**生效，跑著的那一步不換。我們的快照在 {@link ModelSelectionController.assembleStep}（`beforeModel` 那一側，跟換模型通知同一刻），
 *    套用在 {@link createModelSwapMiddleware} 的 `wrapModelCall`（把 `request.model` 換成選中那顆的實例）。
 * 2. **provider／model 變了，下一個請求附一則 user 角色的通知；只換強度不附**（dsh `agent/pre-step`，`sameRoute` 只比 provider 與 model）。
 *    比的是「**最近一次請求實際走的路由**」（`model/start.route`，dsh 的 `requestHeader().config`）對這一步選定的，不是對上一次的選擇。
 *    通知文字逐字照 dsh（{@link modelSwitchNoticeText}），來源標成非 user（#662：不把重複工具提醒的鏈清零）。
 * 3. **沒有東西可換的請求不附通知**：第一次請求沒有「最近一次」，所以不附。
 *
 * ## 與 dsh 的差異（登記）
 *
 * - **通知掛在重複提醒那顆 `beforeModel` 上，不另開一個節點。** dsh 的 `agent/pre-step` 是迴圈裡的一個 waterfall，免費；我們的迴圈是基座的圖，
 *   每一顆 `beforeModel` 是圖裡的一個節點，**每一步多一個 super-step**（`repeat-reminder.ts` 實測過）。重複提醒本來就掛了一顆（出廠開著），
 *   所以通知借它的節點（{@link StepNoticeSource}）。重複提醒被關掉時才另掛一顆（`createStepNoticeMiddleware`，付那一格）。
 * - **通知附加失敗不會重複附。** dsh 寫「失敗在 header 寫入之前，下一個請求再附一次」；我們的通知先進 state、也進日誌，之後的請求都看得到，
 *   所以下一步要擋掉「已經附過、還沒有請求用過」的那種（{@link pendingNotice}），不然會附兩則。
 * - **沒有 `provider`。** 見 `model-route.ts`。
 * - **`beforeModel` 被跳過的那一步（`afterAgent` 的 `jumpTo: 'model'`）沒有通知。** 那一步照樣換模型（`wrapModelCall` 沒有跳過），
 *   通知則要等下一個走過 `beforeModel` 的步；但那時「最近一次請求走的」已經是新的那顆，比不出差別，所以那一次**永遠不附**。
 *   窄：要在插話收尾的那個縫上剛好換模型。
 *
 * @module
 */

import { HumanMessage } from '@langchain/core/messages';
import type { BaseChatModel } from '@langchain/core/language_models/chat_models';
import { createMiddleware } from 'langchain';

import type { AgentMiddleware } from './base-types.js';
import { toLoggedMessage, fromLoggedMessage } from './logged-message.js';
import { messageSourceOf, sourceKwargs } from './message-source.js';
import { normalizeRoute, routeOfModel, sameModel, sameRoute } from './model-route.js';
import type { ModelRoute } from './model-route.js';
import type { SessionLookup } from './registry.js';
import type { SessionLog, SessionEvent } from './session-log.js';

/** 通知那則 `user/message` 的來源 plugin 名，也是 `nexus_source.kind`。 */
export const MODEL_SELECTION_NOTICE_KIND = 'model-selection';

/** 換模型的 middleware 名字。 */
export const MODEL_SELECTION_MIDDLEWARE_NAME = 'nexusModelSelection';

/**
 * 通知文字，**逐字**照 dsh（`model-selection.ts:53`）。
 *
 * @param from - 上一次請求走的模型 id。
 * @param to - 這一步選定的模型 id。
 */
export function modelSwitchNoticeText(from: string, to: string): string {
  return `[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]`;
}

/** 日誌上最後一次請求實際走的路由；一顆都沒有（或舊日誌）是 `undefined`。 */
export function recordedRoute(events: readonly SessionEvent[]): ModelRoute | undefined {
  for (let at = events.length - 1; at >= 0; at -= 1) {
    const event = events[at];
    if (event?.type === 'model/start' && event.data.route !== undefined) {
      return normalizeRoute(event.data.route);
    }
  }
  return undefined;
}

/** 日誌上最後一次使用者的選擇；沒選過是 `undefined`。 */
export function recordedSelection(events: readonly SessionEvent[]): ModelRoute | undefined {
  for (let at = events.length - 1; at >= 0; at -= 1) {
    const event = events[at];
    if (event?.type === 'model/selection') {
      return normalizeRoute({
        model: event.data.modelId,
        ...(event.data.reasoningEffort !== undefined && { effort: event.data.reasoningEffort }),
      });
    }
  }
  return undefined;
}

/**
 * 已經附了這個通知、而且還沒有請求用過它：從尾端往前找，碰到 `model/start` 就停（那之前的通知已經被一次請求看過了）。
 */
export function pendingNotice(events: readonly SessionEvent[], to: string): boolean {
  for (let at = events.length - 1; at >= 0; at -= 1) {
    const event = events[at];
    if (event === undefined) continue;
    if (event.type === 'model/start') return false;
    if (event.type !== 'user/message') continue;
    if (
      event.data.source.kind !== 'plugin' ||
      event.data.source.plugin !== MODEL_SELECTION_NOTICE_KIND
    ) {
      continue;
    }
    const source = messageSourceOf(fromLoggedMessage(event.data.message));
    if (source?.kind === MODEL_SELECTION_NOTICE_KIND && source.to === to) return true;
  }
  return false;
}

/** 組裝點交給控制器的東西：部署預設，與「這條路由的模型實例」。 */
export interface ModelSelectionOptions {
  /** 部署預設的路由（沒選過、日誌上也沒有路由的會話用它）。 */
  readonly defaultRoute: ModelRoute;
  /**
   * 這條路由要用的模型實例（同一條路由回同一個實例，由呼叫端快取）。**回 `undefined` ＝ 沿用 `request.model` 原本那顆**
   * （預設那顆；它在組裝時建好，不為它另建一個實例，也就是沒選過的會話送出去的請求與今天逐欄一致）。
   */
  readonly instanceFor: (route: ModelRoute) => BaseChatModel | undefined;
}

/**
 * 一條會話（root）的模型選擇。**狀態都在日誌上**（`model/selection` 與 `model/start.route`），這個物件只多一格每一步的快照。
 *
 * 一條 thread 一個：serve 每條 thread 各組裝一次，CLI 一個 REPL 一個。
 */
export class ModelSelectionController {
  readonly #options: ModelSelectionOptions;
  #log: SessionLog | undefined;
  #assembled: ModelRoute | undefined;

  constructor(options: ModelSelectionOptions) {
    this.#options = options;
  }

  /** 部署預設。 */
  get defaultRoute(): ModelRoute {
    return normalizeRoute(this.#options.defaultRoute);
  }

  /** 接上 root 的日誌（`registry.sessions.join` 時）。重複接同一份無妨。 */
  attach(log: SessionLog): void {
    this.#log = log;
  }

  /** 日誌上的現況：最近一次請求走的、與使用者最後一次選的（沒有就是 `undefined`）。 */
  state(): { lastUsed: ModelRoute | undefined; selected: ModelRoute | undefined } {
    const events = this.#log?.events ?? [];
    return { lastUsed: recordedRoute(events), selected: recordedSelection(events) };
  }

  /**
   * **下一步會用的路由**：使用者最後選的 → 最近一次請求走的 → 部署預設。
   *
   * 順序照 dsh（`agent.ts:295-298`）：沒選過的會話先沿用日誌裡最後一個請求的路由，再沒有才讀部署預設。選擇不會被「消耗」：選了
   * 之後它一直是這條會話的選擇，直到下一次選；所以不能拿「日誌上哪一顆比較新」判斷（一步開頭快照之後、請求之前才選的，
   * `model/selection` 會落在舊路由的 `model/start` 前面）。
   */
  next(): ModelRoute {
    const { lastUsed, selected } = this.state();
    return selected ?? lastUsed ?? this.defaultRoute;
  }

  /**
   * 記下使用者的選擇。**不驗證**——型錄與強度的檢查在呼叫端（它才有型錄），驗過才能呼叫這裡。
   *
   * @throws 還沒接上日誌：選擇無處可記。
   */
  select(route: ModelRoute): void {
    if (this.#log === undefined) throw new Error('model-selection：還沒接上會話日誌，選擇無處可記');
    const normalized = normalizeRoute(route);
    this.#log.append('model/selection', {
      modelId: normalized.model,
      ...(normalized.effort !== undefined && { reasoningEffort: normalized.effort }),
    });
  }

  /** 一步開頭快照下一步的路由（`beforeModel` 那一側）。同一步的 {@link takeStepRoute} 會用它。 */
  assembleStep(): ModelRoute {
    this.#assembled = this.next();
    return this.#assembled;
  }

  /**
   * 這一步的請求用哪條路由，並清掉快照。沒有快照（`beforeModel` 沒跑到、或重複提醒與通知節點都沒掛）就現算。
   * **清掉是承重的**：留著會讓 `beforeModel` 被跳過的下一步用上一步的舊快照。
   */
  takeStepRoute(): ModelRoute {
    const route = this.#assembled ?? this.next();
    this.#assembled = undefined;
    return route;
  }

  /** 這條路由要用的實例；`undefined` ＝ 沿用 `request.model`。 */
  instanceFor(route: ModelRoute): BaseChatModel | undefined {
    return this.#options.instanceFor(normalizeRoute(route));
  }

  /**
   * 這一步要附的換模型通知。`found` 要是 root 的日誌；只有「最近一次請求走的」跟這一步選定的**模型**不同才附。
   */
  noticeFor(log: SessionLog): readonly HumanMessage[] {
    const route = this.assembleStep();
    const previous = recordedRoute(log.events);
    if (previous === undefined || sameModel(previous, route)) return [];
    if (pendingNotice(log.events, route.model)) return [];
    const message = new HumanMessage({
      content: [{ type: 'text', text: modelSwitchNoticeText(previous.model, route.model) }],
      additional_kwargs: sourceKwargs({
        kind: MODEL_SELECTION_NOTICE_KIND,
        form: 'notice',
        from: previous.model,
        to: route.model,
      }),
    });
    try {
      log.append('user/message', {
        message: toLoggedMessage(message),
        source: { kind: 'plugin', plugin: MODEL_SELECTION_NOTICE_KIND },
      });
    } catch {
      // 記不進去通知照樣送出（同重複提醒）。
    }
    return [message];
  }
}

/**
 * 請求上記「換模型之前那顆」的鍵（#1377）。換模型（root 一顆、子代理跟隨一顆）把 `request.model` 換成選中的實例時，原本那顆
 * 記在這裡——排在它們裡面的摘要器要找回它：換模型那一步由**最近一次已送出的請求**那顆（常常就是它）生摘要，而選中的實例之外
 * 沒有別的路可以拿到預設那顆（`instanceFor` 對預設路由回 `undefined`）。
 *
 * 用 `Symbol.for` 的可列舉屬性，是因為沿路的 `{ ...request, ... }` 會把它帶下去；不用弱引用表是因為那要以請求物件為鍵，而請求
 * 物件每一層都在重建。
 */
const ROUTED_FROM = Symbol.for('nexus.model-selection.routed-from');

/** 把請求換成 `instance`，並記下換之前那顆（見 {@link ROUTED_FROM}）。 */
function routed<T extends { model?: unknown }>(request: T, instance: BaseChatModel): T {
  return { ...request, model: instance, [ROUTED_FROM]: routedFromOf(request) } as T;
}

/**
 * 這個請求被換模型之前的 `model`；沒被換過（選中的就是預設那顆）就是 `request.model` 本身。
 *
 * @param request - 任何帶 `model` 的請求。
 */
export function routedFromOf(request: { model?: unknown }): unknown {
  return (request as Record<symbol, unknown>)[ROUTED_FROM] ?? request.model;
}

/**
 * 換模型的 middleware：每一步把 `request.model` 換成這一步選定的那顆。**只折進 root**（`fold.ts` 的 `rootOnly`）。
 *
 * 排在摘要器、起訖與用量記錄器的**外面**：它們看到的 `request.model` 就是選中的那顆（摘要用它生、`model/start.route` 讀它的標籤、
 * 估算的錨按它的名字認）。選中的就是預設那顆時什麼都不換，請求逐欄與沒有這顆 middleware 時一樣。
 *
 * **「外面」是組裝時搬出來的**（#1369）：摘要器同名取代回預設疊第三格，新名字原本一律排在它後面；
 * `agent-assembly.ts` 的 `mergeMiddlewareStack` 把這一顆搬到預設疊前面。只在 fold 的槽位表裡排前面不夠。
 *
 * @param controller - 這條會話的控制器。
 */
export function createModelSwapMiddleware(controller: ModelSelectionController): AgentMiddleware {
  return createMiddleware({
    name: MODEL_SELECTION_MIDDLEWARE_NAME,
    wrapModelCall: (request, handler) => {
      const route = controller.takeStepRoute();
      const instance = controller.instanceFor(route);
      // 預設那顆（`instanceFor` 回 `undefined`）不換：沒選過的會話送出去的請求與沒有這顆 middleware 時逐欄一樣。
      if (instance === undefined || instance === request.model) return handler(request);
      return handler(routed(request, instance));
    },
  }) as unknown as AgentMiddleware;
}

/** 子代理跟隨會話選擇的 middleware 名字；背景圖有自己指定的模型時要把它濾掉（`compileSubagentGraph`）。 */
export const SUBAGENT_MODEL_FOLLOW_MIDDLEWARE_NAME = 'nexusSubagentModelFollow';

/** 一個子代理定義自己釘住的那兩格（見 `NexusSubAgent`）。 */
export interface SubagentModelPin {
  /** 型錄 id。省略＝父代理當下那顆。 */
  readonly model?: string;
  /** 推理強度。省略＝換了模型就用新模型的預設；沒換模型就沿用父代理當下的強度。 */
  readonly reasoningEffort?: string;
}

/**
 * 子代理的換模型 middleware（[#328](https://github.com/DemianLi/nexus-agent/issues/328) 第 3 項）：每次叫模型前，把 `request.model` 換成這個子代理**此刻**該用的那顆。
 *
 * 路由的優先序：**定義自己釘的（`pin`）> 父代理當下的選擇（{@link ModelSelectionController.next}，#723）> 部署預設**。
 * 前兩者之間照 dsh `requestedAgentOptions`（`tool-subagent/src/model-selection.ts:99-128`）的合併：釘了 `model` 沒釘強度＝新模型的預設強度
 * （dsh 的 `routeChanged && 沒給強度` 把設定的強度丟掉）；只釘強度＝父代理當下的模型換這個強度。
 *
 * 與 {@link createModelSwapMiddleware} 的差別：**不碰那一步的快照**（`takeStepRoute` 是 root 每步一次的消耗品，子代理一步可以叫很多次模型，
 * 也可能與 root 同時在跑），直接讀 {@link ModelSelectionController.next} 現算。
 *
 * 選中的就是預設那顆（`instanceFor` 回 `undefined`）時什麼都不換，請求逐欄與沒有這顆 middleware 時一樣。
 *
 * @param controller - 這條會話的控制器（子代理圖與 root 同一次組裝，同一個）。
 * @param pin - 定義釘住的兩格；省略＝純跟隨。
 */
export function createSubagentModelFollowMiddleware(
  controller: ModelSelectionController,
  pin: SubagentModelPin = {},
): AgentMiddleware {
  return createMiddleware({
    name: SUBAGENT_MODEL_FOLLOW_MIDDLEWARE_NAME,
    wrapModelCall: (request, handler) => {
      const parent = controller.next();
      const route: ModelRoute =
        pin.model !== undefined
          ? {
              model: pin.model,
              ...(pin.reasoningEffort !== undefined && { effort: pin.reasoningEffort }),
            }
          : pin.reasoningEffort !== undefined
            ? { model: parent.model, effort: pin.reasoningEffort }
            : parent;
      const instance = controller.instanceFor(route);
      if (instance === undefined || instance === request.model) return handler(request);
      return handler(routed(request, instance));
    },
  }) as unknown as AgentMiddleware;
}

/** 摘要器問「這一次生摘要用哪一顆」時交的請求（只用到這幾格）。 */
interface SummaryModelRequest {
  readonly model?: unknown;
  readonly runtime?: { readonly configurable?: unknown };
}

/**
 * 摘要用哪一顆生（[#1377](https://github.com/DemianLi/nexus-agent/issues/1377)）：**最近一次已送出的請求那顆，沒有就退回
 * 這個 agent 換模型之前的那顆**——照 dsh `summarizeWithLlm` 的目標 `configured ?? latest ?? agentTarget`
 * （`compaction-basic/src/summarizer.ts:127-137`，`latest` 是 `session.requestHeader()?.config`；`configured` 不在這一張）。
 *
 * ## 為什麼摘要跟最近一次，門檻卻跟選中那顆
 *
 * 門檻在換模型那一步就跟著選中那顆夾窗（#1369，比 dsh 早一步：dsh 的壓縮在 `agent/pre-step`、早於路由，那一步必定先撞一次
 * overflow）；生摘要則仍用最近一次已送出的那顆——換模型那一步它還是舊的、裝得下整段歷史的那顆，選中的小窗口那顆收到的是
 * 摘要後的請求。**門檻跟選中那顆是偏離 dsh（#1378 登記、PM 接受，理由是 #723 的驗收），生摘要跟 `latest` 是照 dsh。**
 *
 * ## 讀哪一份日誌
 *
 * 這次呼叫**自己的**日誌（`sessions.forCall`，與 `model/usage`、`compaction/summary` 同一把鑰匙）：root 讀 root 的，
 * 子代理讀自己的——就是 dsh 的 `agent.session`。背景圖（`follow: false`）的請求一路走委派時那顆，所以它的「最近一次」
 * 就是它自己，不跟使用者後來換的。讀不到日誌時退回控制器上 root 的 `lastUsed`。
 *
 * ## 實例從哪來
 *
 * - 路由與這個 agent 換模型之前那顆（{@link routedFromOf}）同一條：就用那一個實例（背景圖委派時給的、預設那顆都走這裡，
 *   不另建、不丟掉它身上的重試與逾時包裝）。
 * - 否則 `controller.instanceFor(route)`（同一條路由回同一個實例）；它回 `undefined`（預設路由）就退回換模型之前那顆。
 *
 * **不准拋**：這一層坐在同名取代的摘要器裡，漏出去的錯等於把摘要器拔掉。路由已不在型錄（`instanceFor` 拋）或日誌讀不到，
 * 一律回 `undefined`——呼叫端退回 `request.model`（選中那顆）。
 *
 * @param controller - 這條會話的控制器。
 * @param sessions - 註冊表的 `sessions` 通道。
 * @returns 問「這次生摘要用哪顆」；`undefined` ＝ 沒有意見，用 `request.model`。
 */
export function summaryModelOf(
  controller: ModelSelectionController,
  sessions: { forCall(config: unknown): SessionLookup },
): (request: SummaryModelRequest) => unknown {
  return (request) => {
    try {
      const base = routedFromOf(request);
      let route: ModelRoute | undefined;
      const found = sessions.forCall({ configurable: request.runtime?.configurable });
      if (found.kind === 'ok') route = recordedRoute(found.log.events);
      route ??= controller.state().lastUsed;
      if (route === undefined) return base;
      const baseRoute = routeOfModel(base);
      if (baseRoute !== undefined && sameRoute(baseRoute, route)) return base;
      return controller.instanceFor(route) ?? base;
    } catch {
      return undefined;
    }
  };
}
